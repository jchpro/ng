// Turns the highlight.js themes the docs-app uses into SCSS partials that expose each as a mixin, so
// the code example component can `@use` them instead of `@import`ing the package's files (Sass
// deprecates `@import`). The themes are plain CSS, so wrapping one in `@mixin theme { … }` and
// including it where the `@import` was produces the same rules.
//
//   npm run generate:hljs-themes           writes the partials
//   npm run generate:hljs-themes -- --check  fails when they differ from what the installed highlight.js
//                                            would generate (part of `npm test`)
//
// After upgrading highlight.js, run the first, review the diff, commit the partials.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'node_modules', 'highlight.js', 'scss');
const target = join(root, 'projects', 'docs-app', 'src', 'app', 'docs', 'code-example', 'hljs');

// Theme file of highlight.js -> the partial that wraps it.
const themes = ['github', 'github-dark'];

function generate(theme) {
  const input = join(source, `${theme}.scss`);
  const css = readFileSync(input, 'utf8').replace(/\r\n/g, '\n').trim();
  const indented = css.split('\n').map((line) => (line ? `  ${line}` : line)).join('\n');
  const version = JSON.parse(readFileSync(join(root, 'node_modules', 'highlight.js', 'package.json'), 'utf8')).version;
  return [
    `// Generated by scripts/generate-hljs-themes.mjs from highlight.js ${version} (scss/${theme}.scss).`,
    '// Do not edit: run `npm run generate:hljs-themes`.',
    '//',
    '// The theme as a mixin, for `@use` (the package file is plain CSS meant for `@import`).',
    '@mixin theme {',
    indented,
    '}',
    ''
  ].join('\n');
}

const check = process.argv.includes('--check');
const outdated = [];

for (const theme of themes) {
  const file = join(target, `_${theme}.scss`);
  const expected = generate(theme);
  const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : undefined;
  if (current === expected) {
    continue;
  }
  if (check) {
    outdated.push(file.slice(root.length));
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, expected);
  console.log(`wrote ${file.slice(root.length)}`);
}

if (outdated.length) {
  console.error(`The highlight.js theme partials are out of date:\n${outdated.map((file) => `  ${file}`).join('\n')}\nRun \`npm run generate:hljs-themes\` and commit the result.`);
  process.exit(1);
}
if (check) {
  console.log('The highlight.js theme partials match the installed highlight.js.');
}
